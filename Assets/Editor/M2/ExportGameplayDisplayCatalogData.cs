            AppendFileHash(sb, "tblevel", fileHashes, "tblevel.json");
            AppendFileHash(sb, "tbgathernode", fileHashes, "tbgathernode.json");
            AppendFileHash(sb, "tbmapinstance", fileHashes, "tbmapinstance.json");
