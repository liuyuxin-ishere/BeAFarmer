        static Dictionary<int, string> BuildUnlockHints(List<ItemRow> items, GameConfigSnapshot snap)
        {
            var byLevel = new Dictionary<int, List<string>>();
            for (int i = 0; i < items.Count; i++)
            {
                ItemRow row = items[i];
                if (row.Type != "Tool" || row.UnlockLevel <= 1)
                    continue;
                AddHint(byLevel, row.UnlockLevel, "解锁" + row.Name);
            }

            for (int i = 0; i < snap.PlotStages.Count; i++)
            {
                var stage = snap.PlotStages[i];
                if (stage.Stage <= 0)
                    continue;
                AddHint(byLevel, stage.NeedPlayerLevel,
                    "地块可扩至" + stage.TotalPlots.ToString(CultureInfo.InvariantCulture));
            }

            var result = new Dictionary<int, string>();
            foreach (KeyValuePair<int, List<string>> pair in byLevel)
            {
                string joined = string.Join("；", pair.Value);
                result[pair.Key] = "Lv." + pair.Key.ToString(CultureInfo.InvariantCulture) + " " + joined;
            }
            return result;
        }

        static void AddHint(Dictionary<int, List<string>> map, int level, string text)
        {
            if (!map.TryGetValue(level, out List<string> list))
            {
                list = new List<string>();
                map[level] = list;
            }
            if (!list.Contains(text))
                list.Add(text);
        }

        static List<ItemRow> LoadItems(string path, GameConfigSnapshot snap)
        {
            var list = new List<ItemRow>();
            foreach (SimpleJson.Obj row in SimpleJson.ParseArray(File.ReadAllText(path, Encoding.UTF8)))
            {
                int id = GameConfigSnapshot.ToConfigInt32(row.RequireLong("id"), path + ".id");
                if (!snap.IsKnownItem(id))
                    throw new InvalidOperationException("tbitem id not in KnownItemIds: " + id);
                string type = row.RequireString("type");
                int stackMax = GameConfigSnapshot.ToConfigInt32(row.RequireLong("stackMax"), path + ".stackMax");
                int sellPrice = GameConfigSnapshot.ToConfigInt32(row.RequireLong("sellPrice"), path + ".sellPrice");
                int unlock = GameConfigSnapshot.ToConfigInt32(row.RequireLong("unlockLevel"), path + ".unlockLevel");
                string name = row.RequireString("name");
                if (type != "Currency")
                {
                    if (!snap.TryGetItemStackMax(id, out int expectedStack) || expectedStack != stackMax)
                        throw new InvalidOperationException("stackMax mismatch id=" + id);
                }
                else if (snap.TryGetItemStackMax(id, out _))
                {
                    throw new InvalidOperationException("Currency must not enter ItemStackMax id=" + id);
                }

                bool sellable = snap.IsSellable(id);
                if (sellable && sellPrice <= 0)
                    throw new InvalidOperationException("sellable but sellPrice<=0 id=" + id);
                if (!sellable && type != "Currency" && sellPrice > 0)
                    throw new InvalidOperationException("positive sellPrice but not IsSellable id=" + id);

                list.Add(new ItemRow(id, name, type, stackMax, sellPrice, unlock));
            }
            list.Sort((a, b) => a.Id.CompareTo(b.Id));
            return list;
        }

        static Dictionary<string, string> ReadManifestFileHashes(string path)
        {
            if (!File.Exists(path))
                throw new FileNotFoundException("config_manifest missing", path);
            string text = File.ReadAllText(path, Encoding.UTF8);
            var map = new Dictionary<string, string>(StringComparer.Ordinal);
            // 轻量解析 files[].name / sha256，避免额外 JSON 依赖。
            int idx = 0;
            while (true)
            {
                int nameAt = text.IndexOf("\"name\":", idx, StringComparison.Ordinal);
                if (nameAt < 0)
                    break;
                int nameStart = text.IndexOf('"', nameAt + 7);
                if (nameStart < 0)
                    break;
                nameStart++;
                int nameEnd = text.IndexOf('"', nameStart);
                if (nameEnd < 0)
                    break;
                string name = text.Substring(nameStart, nameEnd - nameStart);
                int shaAt = text.IndexOf("\"sha256\":", nameEnd, StringComparison.Ordinal);
                if (shaAt < 0 || shaAt > nameEnd + 120)
                {
                    idx = nameEnd + 1;
                    continue;
                }
                int shaStart = text.IndexOf('"', shaAt + 9);
                if (shaStart < 0)
                    break;
                shaStart++;
                int shaEnd = text.IndexOf('"', shaStart);
                if (shaEnd < 0)
                    break;
                string sha = text.Substring(shaStart, shaEnd - shaStart);
                map[name] = sha;
                idx = shaEnd + 1;
            }
            if (map.Count == 0)
                throw new InvalidOperationException("manifest files empty");
            return map;
        }

        static void VerifyFileHash(string path, Dictionary<string, string> manifest, string fileName)
        {
            if (!manifest.TryGetValue(fileName, out string expected))
                throw new InvalidOperationException("manifest missing " + fileName);
            string actual = Sha256File(path);
            if (!string.Equals(actual, expected, StringComparison.OrdinalIgnoreCase))
                throw new InvalidOperationException(
                    "hash mismatch " + fileName + " expected=" + expected + " actual=" + actual);
        }

        static void AppendFileHash(StringBuilder sb, string key, Dictionary<string, string> map, string fileName)
        {
            if (!map.TryGetValue(fileName, out string sha))
                throw new InvalidOperationException("manifest missing " + fileName);
            sb.Append("      ").Append(key).Append(" = \"").Append(sha).AppendLine("\",");
        }

        static string LuaString(string value)
        {
            string s = value ?? "";
            s = s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n").Replace("\r", "");
            return "\"" + s + "\"";
        }

        static string Sha256File(string path)
        {
            using (var sha = SHA256.Create())
            using (var fs = File.OpenRead(path))
            {
                byte[] hash = sha.ComputeHash(fs);
                var sb = new StringBuilder(hash.Length * 2);
                for (int i = 0; i < hash.Length; i++)
                    sb.Append(hash[i].ToString("x2", CultureInfo.InvariantCulture));
                return sb.ToString();
            }
        }

        /// <summary>
        /// 从客户端 tbgathernode 装载展示名/冷却；与 snap.GatherNodes 交叉校验 tool/unlock/cooldown。
        /// </summary>
        static List<GatherDisplayRow> LoadGatherDisplayRows(string path, GameConfigSnapshot snap)
        {
            var list = new List<GatherDisplayRow>();
            foreach (SimpleJson.Obj row in SimpleJson.ParseArray(File.ReadAllText(path, Encoding.UTF8)))
            {
                int id = GameConfigSnapshot.ToConfigInt32(row.RequireLong("id"), path + ".id");
                if (!snap.TryGetGatherNode(id, out GatherNodeSpec spec))
                    throw new InvalidOperationException("gather id not in snapshot: " + id);
                string code = row.RequireString("code");
                string name = row.RequireString("name");
                int toolId = GameConfigSnapshot.ToConfigInt32(row.RequireLong("toolId"), path + ".toolId");
                int unlock = GameConfigSnapshot.ToConfigInt32(row.RequireLong("unlockLevel"), path + ".unlockLevel");
                int cooldown = GameConfigSnapshot.ToConfigInt32(row.RequireLong("cooldownSec"), path + ".cooldownSec");
                if (toolId != spec.ToolId || unlock != spec.UnlockLevel || cooldown != spec.CooldownSec)
                    throw new InvalidOperationException("gather display mismatch id=" + id);
                list.Add(new GatherDisplayRow(id, code, name, toolId, unlock, cooldown));
            }
            list.Sort((a, b) => a.Id.CompareTo(b.Id));
            if (list.Count != snap.GatherNodes.Count)
                throw new InvalidOperationException(
                    "gather count mismatch export=" + list.Count + " snap=" + snap.GatherNodes.Count);
            return list;
        }

        /// <summary>
        /// MapInstance.Node → 展示行；玩家可读中文标签（类型名+甲乙丙…），不直出 tree_a 技术标签。
        /// </summary>
        static List<MapNodeDisplayRow> BuildMapNodeDisplayRows(
            GameConfigSnapshot snap,
            List<GatherDisplayRow> gatherNodes)
        {
            var nameByType = new Dictionary<int, string>();
            for (int i = 0; i < gatherNodes.Count; i++)
                nameByType[gatherNodes[i].Id] = gatherNodes[i].Name;

            var nodes = new List<MapInstanceRow>();
            foreach (KeyValuePair<int, MapInstanceRow> kv in snap.MapInstances)
            {
                if (kv.Value.Kind == "Node")
                    nodes.Add(kv.Value);
            }
            nodes.Sort((a, b) => a.InstanceId.CompareTo(b.InstanceId));
            if (nodes.Count != 13)
                throw new InvalidOperationException("map node count expected 13 got " + nodes.Count);

            var ordinalByType = new Dictionary<int, int>();
            var list = new List<MapNodeDisplayRow>(nodes.Count);
            for (int i = 0; i < nodes.Count; i++)
            {
                MapInstanceRow row = nodes[i];
                if (!nameByType.TryGetValue(row.TypeId, out string typeName))
                    throw new InvalidOperationException("map node type missing gather: " + row.TypeId);
                if (!ordinalByType.TryGetValue(row.TypeId, out int ord))
                    ord = 0;
                ord++;
                ordinalByType[row.TypeId] = ord;
                string label = typeName + OrdinalSuffix(ord);
                list.Add(new MapNodeDisplayRow(row.InstanceId, row.TypeId, label));
            }
            return list;
        }

        static string OrdinalSuffix(int ordinal)
        {
            switch (ordinal)
            {
                case 1: return "甲";
                case 2: return "乙";
                case 3: return "丙";
                case 4: return "丁";
                case 5: return "戊";
                case 6: return "己";
                case 7: return "庚";
                case 8: return "辛";
                default: return ordinal.ToString(CultureInfo.InvariantCulture);
            }
        }

        /// <summary>完整材料/门槛/金币；costComplete 同源 HasCompleteUpgradeCost。</summary>
        static List<ToolLevelDisplayRow> BuildToolLevelDisplayRows(GameConfigSnapshot snap)
        {
            var list = new List<ToolLevelDisplayRow>();
            foreach (KeyValuePair<long, ToolLevelSpec> kv in snap.ToolLevels)
            {
                ToolLevelSpec t = kv.Value;
                var mats = new List<MaterialDisplayRow>(t.Materials.Count);
                for (int i = 0; i < t.Materials.Count; i++)
                {
                    ItemStackSpec m = t.Materials[i];
                    mats.Add(new MaterialDisplayRow(m.ItemId, m.Count));
                }
                list.Add(new ToolLevelDisplayRow(
                    t.ToolId, t.Level, t.NeedPlayerLevel, t.GoldCost, mats, t.HasCompleteUpgradeCost));
            }
            list.Sort((a, b) =>
            {
                int c = a.ToolId.CompareTo(b.ToolId);
                return c != 0 ? c : a.Level.CompareTo(b.Level);
            });
            if (list.Count == 0)
                throw new InvalidOperationException("toolLevels empty");
            return list;
        }

        static void AppendMaterialsLua(StringBuilder sb, IReadOnlyList<MaterialDisplayRow> mats)
        {
            if (mats == null)
            {
                sb.Append("nil");
                return;
            }
            sb.Append("{");
            for (int i = 0; i < mats.Count; i++)
            {
                if (i > 0)
                    sb.Append(", ");
                sb.Append("{ itemId = ").Append(mats[i].ItemId.ToString(CultureInfo.InvariantCulture));
                sb.Append(", count = ").Append(mats[i].Count.ToString(CultureInfo.InvariantCulture));
                sb.Append(" }");
            }
            sb.Append("}");
        }

        sealed class ItemRow
        {
            public ItemRow(int id, string name, string type, int stackMax, int sellPrice, int unlockLevel)
            {
                Id = id;
                Name = name;
                Type = type;
                StackMax = stackMax;
                SellPrice = sellPrice;
                UnlockLevel = unlockLevel;
            }

            public int Id { get; }
            public string Name { get; }
            public string Type { get; }
            public int StackMax { get; }
            public int SellPrice { get; }
            public int UnlockLevel { get; }
        }

        sealed class GatherDisplayRow
        {
            public GatherDisplayRow(int id, string code, string name, int toolId, int unlockLevel, int cooldownSec)
            {
                Id = id;
                Code = code ?? "";
                Name = name ?? "";
                ToolId = toolId;
                UnlockLevel = unlockLevel;
                CooldownSec = cooldownSec;
            }

            public int Id { get; }
            public string Code { get; }
            public string Name { get; }
            public int ToolId { get; }
            public int UnlockLevel { get; }
            public int CooldownSec { get; }
        }

        sealed class MapNodeDisplayRow
        {
            public MapNodeDisplayRow(int instanceId, int typeId, string label)
            {
                InstanceId = instanceId;
                TypeId = typeId;
                Label = label ?? "";
            }

            public int InstanceId { get; }
            public int TypeId { get; }
            public string Label { get; }
        }

        sealed class MaterialDisplayRow
        {
            public MaterialDisplayRow(int itemId, int count)
            {
                ItemId = itemId;
                Count = count;
            }

            public int ItemId { get; }
            public int Count { get; }
        }

        sealed class ToolLevelDisplayRow
        {
            public ToolLevelDisplayRow(
                int toolId,
                int level,
                int needPlayerLevel,
                int goldCost,
                List<MaterialDisplayRow> materials,
                bool costComplete)
            {
                ToolId = toolId;
                Level = level;
                NeedPlayerLevel = needPlayerLevel;
                GoldCost = goldCost;
                Materials = materials ?? new List<MaterialDisplayRow>();
                CostComplete = costComplete;
            }

            public int ToolId { get; }
            public int Level { get; }
            public int NeedPlayerLevel { get; }
            public int GoldCost { get; }
            public List<MaterialDisplayRow> Materials { get; }
            public bool CostComplete { get; }
        }
    }
