        /// <summary>批处理：-executeMethod Game.Editor.M2.ExportGameplayDisplayCatalogData.ExportBatch</summary>
        public static void ExportBatch()
        {
            try
            {
                if (EditorUtility.scriptCompilationFailed)
                    throw new InvalidOperationException("scriptCompilationFailed");
                string path = Export();
                Debug.Log("[T026] GameplayDisplayCatalogData exported: " + path);
                EditorApplication.Exit(0);
            }
            catch (Exception ex)
