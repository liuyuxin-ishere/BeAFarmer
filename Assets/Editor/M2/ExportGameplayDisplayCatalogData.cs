            VerifyFileHash(shopPath, fileHashes, "tbshop.json");
            VerifyFileHash(plotPath, fileHashes, "tbplot.json");
            VerifyFileHash(gatherPath, fileHashes, "tbgathernode.json");
            VerifyFileHash(mapPath, fileHashes, "tbmapinstance.json");
